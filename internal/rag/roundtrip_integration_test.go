// Regression test for the resume feature's Qdrant ID round-trip.
//
// Prerequisites:
//   docker run -d --name qdrant -p 6333:6333 -p 6334:6334 qdrant/qdrant:v1.17.1
//
// Run:
//   go test -tags integration -v ./internal/rag/ -run TestExistingPoints

package rag

import (
	"context"
	"testing"
	"time"
)

// TestExistingPointsRoundTrip pins the functional contract the resume
// feature depends on: point IDs generated by pointID must round-trip
// through a real Qdrant — upsert writes the point under the ID, and
// ExistingPoints finds it keyed by the SAME input ID string. A failure
// here means every resume lookup misses and every chunk re-embeds on
// every run (the quota-burning behavior this feature exists to prevent).
func TestExistingPointsRoundTrip(t *testing.T) {
	ctx, cancel := context.WithTimeout(context.Background(), time.Minute)
	defer cancel()

	qClient, err := NewQdrantClient(testQdrantAddr)
	if err != nil {
		t.Fatalf("connecting to qdrant (is it running?): %v", err)
	}
	defer func() { _ = qClient.Close() }()

	const collection = "existing_points_roundtrip_test"
	const dimensions = 2
	if err := qClient.EnsureCollection(ctx, collection, dimensions); err != nil {
		t.Fatalf("ensuring collection: %v", err)
	}

	// Upsert two chunks using the production pointID scheme.
	ids := []string{
		pointID("doc-a", 0),
		pointID("doc-a", 1),
	}
	points := []Point{
		{ID: ids[0], Vector: []float32{1, 1}, Payload: map[string]any{"doc_id": "doc-a", "content_hash": contentHash("alpha")}},
		{ID: ids[1], Vector: []float32{2, 2}, Payload: map[string]any{"doc_id": "doc-a", "content_hash": contentHash("beta")}},
	}
	if err := qClient.Upsert(ctx, collection, points); err != nil {
		t.Fatalf("upserting: %v", err)
	}

	// Both written points must be found, keyed by the exact input IDs.
	existing, err := qClient.ExistingPoints(ctx, collection, ids)
	if err != nil {
		t.Fatalf("ExistingPoints: %v", err)
	}
	for _, id := range ids {
		hash, ok := existing[id]
		if !ok {
			t.Errorf("point %q (written via Upsert) not found in ExistingPoints result %v — resume lookup keys don't round-trip", id, existing)
			continue
		}
		if hash == "" {
			// OK for points written before content hashing; here payloads carry hashes.
			t.Errorf("point %q found but content_hash payload missing", id)
		}
	}

	// A chunk never written must be absent (resume would embed it).
	missing := pointID("doc-a", 2)
	if _, ok := existing[missing]; ok {
		t.Errorf("unwritten point %q reported as existing", missing)
	}

	// Cross-check with the production pendingChunks filter, pre-hash-era path:
	// a point stored WITHOUT a content_hash payload must be reported as
	// pending (re-embedded once), not silently skipped.
	legacyID := pointID("doc-legacy", 0)
	if err := qClient.Upsert(ctx, collection, []Point{{ID: legacyID, Vector: []float32{3, 3}, Payload: map[string]any{"doc_id": "doc-legacy"}}}); err != nil {
		t.Fatalf("upserting legacy point: %v", err)
	}
	existing, err = qClient.ExistingPoints(ctx, collection, []string{legacyID})
	if err != nil {
		t.Fatalf("ExistingPoints (legacy): %v", err)
	}
	if hash, ok := existing[legacyID]; !ok || hash != "" {
		t.Errorf("legacy point round-trip: got %v, want present with empty hash", existing)
	}
	if todo := pendingChunks([]Chunk{{DocID: "doc-legacy", Index: 0, Text: "x"}}, existing); len(todo) != 1 {
		t.Errorf("legacy point must be re-embedded (todo=1), got %d", len(todo))
	}

	// Cleanup so repeated runs start fresh.
	_ = qClient.client.DeleteCollection(ctx, collection)
}
