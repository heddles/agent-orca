package controller

import (
	"context"
	"testing"

	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
	"k8s.io/apimachinery/pkg/runtime"
	"sigs.k8s.io/controller-runtime/pkg/client"
	"sigs.k8s.io/controller-runtime/pkg/client/fake"

	agentorcav1alpha1 "github.com/heddles/agent-orca/api/v1alpha1"
	"github.com/heddles/agent-orca/internal/tenancy"
)

func TestUIOwnerMigration(t *testing.T) {
	scheme := runtime.NewScheme()
	if err := agentorcav1alpha1.AddToScheme(scheme); err != nil {
		t.Fatal(err)
	}
	const managed = "app.kubernetes.io/managed-by"
	controlled := []metav1.OwnerReference{{APIVersion: "agentorca.agentorca.io/v1alpha1", Kind: "Agent", Name: "p", UID: "u", Controller: new(true)}}

	mk := func(name string, labels, annotations map[string]string, owners []metav1.OwnerReference) *agentorcav1alpha1.Tool {
		return &agentorcav1alpha1.Tool{ObjectMeta: metav1.ObjectMeta{
			Name: name, Namespace: "ns", Labels: labels, Annotations: annotations, OwnerReferences: owners,
		}}
	}
	ui := map[string]string{managed: "agent-orca"}

	tests := []struct {
		name      string
		obj       client.Object
		wantOwner string // the owner annotation afterwards
		wantLabel bool   // the managed-by label afterwards
	}{
		{"made by the old UI API: converted", mk("ui-made", ui, nil, nil), "ui", false},
		{"keeps its other labels and annotations", mk("with-extras", map[string]string{managed: "agent-orca", "team": "x"}, map[string]string{"note": "y"}, nil), "ui", false},
		{"made by a controller: left alone", mk("controller-made", ui, nil, controlled), "", true},
		{"already annotated: left alone", mk("annotated", ui, map[string]string{tenancy.AnnotationOwner: "git"}, nil), "git", true},
		{"no label: left alone", mk("plain", nil, nil, nil), "", false},
		{"someone else's managed-by value: left alone", mk("helm", map[string]string{managed: "Helm"}, nil, nil), "", true},
		{"argo-tracked: ambiguous", mk("argo", ui, map[string]string{"argocd.argoproj.io/tracking-id": "app:x"}, nil), "", true},
		{"flux-tracked: ambiguous", mk("flux", map[string]string{managed: "agent-orca", "kustomize.toolkit.fluxcd.io/name": "apps"}, nil, nil), "", true},
		{"helm-release annotated: ambiguous", mk("helm-release", ui, map[string]string{"meta.helm.sh/release-name": "r"}, nil), "", true},
		{"platform-shared: ambiguous", mk("platform", map[string]string{managed: "agent-orca", tenancy.LabelScope: tenancy.ScopePlatform}, nil, nil), "", true},
		{"generated by an MCPServer: ambiguous", mk("generated", map[string]string{managed: "agent-orca", LabelManagedBy: LabelManagedByMCPServer}, nil, nil), "", true},
		{"workflow: ambiguous (agents create them too)", &agentorcav1alpha1.AgentWorkflow{ObjectMeta: metav1.ObjectMeta{Name: "wf", Namespace: "ns", Labels: ui}}, "", true},
		{"deployment: converted", &agentorcav1alpha1.AgentDeployment{ObjectMeta: metav1.ObjectMeta{Name: "dep", Namespace: "ns", Labels: ui}}, "ui", false},
		{"deployment owned by a controller: left alone", &agentorcav1alpha1.AgentDeployment{ObjectMeta: metav1.ObjectMeta{Name: "dep-ctl", Namespace: "ns", Labels: ui, OwnerReferences: controlled}}, "", true},
		{"agent: converted", &agentorcav1alpha1.Agent{ObjectMeta: metav1.ObjectMeta{Name: "ag", Namespace: "ns", Labels: ui}}, "ui", false},
	}
	objs := make([]client.Object, 0, len(tests))
	for _, tt := range tests {
		objs = append(objs, tt.obj)
	}
	c := fake.NewClientBuilder().WithScheme(scheme).WithObjects(objs...).Build()

	stats, err := (&UIOwnerMigration{Client: c}).Run(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	if stats.Converted != 4 || stats.Ambiguous != 6 {
		t.Errorf("stats = %+v, want 3 converted and 6 ambiguous", stats)
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := tt.obj.DeepCopyObject().(client.Object)
			if err := c.Get(context.Background(), client.ObjectKeyFromObject(tt.obj), got); err != nil {
				t.Fatal(err)
			}
			if owner := tenancy.OwnerOf(got); owner != tt.wantOwner {
				t.Errorf("owner annotation = %q, want %q", owner, tt.wantOwner)
			}
			if _, has := got.GetLabels()[managed]; has != tt.wantLabel {
				t.Errorf("managed-by label present = %v, want %v", has, tt.wantLabel)
			}
		})
	}

	// Other labels and annotations survive the conversion.
	var extras agentorcav1alpha1.Tool
	if err := c.Get(context.Background(), client.ObjectKey{Namespace: "ns", Name: "with-extras"}, &extras); err != nil {
		t.Fatal(err)
	}
	if extras.Labels["team"] != "x" || extras.Annotations["note"] != "y" {
		t.Errorf("conversion dropped metadata: %v %v", extras.Labels, extras.Annotations)
	}

	// A second pass has nothing left to convert.
	again, err := (&UIOwnerMigration{Client: c}).Run(context.Background())
	if err != nil || again.Converted != 0 {
		t.Errorf("second pass = %+v, %v", again, err)
	}
}
