package controller

import (
	"context"
	"fmt"
	"log/slog"

	"k8s.io/apimachinery/pkg/api/meta"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
	"sigs.k8s.io/controller-runtime/pkg/client"

	agentorcav1alpha1 "github.com/heddles/agent-orca/api/v1alpha1"
	"github.com/heddles/agent-orca/internal/security"
	"github.com/heddles/agent-orca/internal/tenancy"
)

// UIOwnerMigration is a one-shot pass, run by the leader when the operator
// starts, that converts the objects the old UI API created to the ownership
// annotation.
//
// The old UI API stamped app.kubernetes.io/managed-by: agent-orca on every
// object it created or updated that lacked the label, and its delete guard
// trusted that label. Controllers use the same label, so it could not tell
// "made in the UI" from "made by a controller". The UI API now owns an object
// when it carries agentorca.io/owner: ui, and this pass gives that annotation
// (and drops the label) to the objects the old API made.
//
// An object the old API made has the label and no controller owner reference.
// That test is not enough for every object, so a pass logs and leaves alone:
//
//   - an AgentWorkflow: agents create workflows through the internal API with
//     the same label and no owner reference, so a workflow with the label may
//     be an agent's, not a person's;
//   - a platform-shared object, which the UI API can never create;
//   - an object a GitOps tool tracks (Argo CD, Flux, Helm): the old API stamped
//     the label onto those too, and they belong to Git, not the UI. Stage U2
//     decides what to do with them;
//   - a Tool generated by an MCPServer.
//
// Each of those is reported at info level with its kind, namespace and name, so
// an operator can annotate the ones that are the UI's by hand.
//
// It is safe to run on every start: it only touches objects that still have the
// label and no owner annotation.
type UIOwnerMigration struct {
	// Client reads and patches; see TenantBackfill.Client.
	Client client.Client
}

// UIOwnerMigrationStats is what one pass did.
type UIOwnerMigrationStats struct {
	Converted int
	Ambiguous int
}

// NeedLeaderElection makes only the leader run the pass.
func (m *UIOwnerMigration) NeedLeaderElection() bool { return true }

// Start implements manager.Runnable.
func (m *UIOwnerMigration) Start(ctx context.Context) error {
	stats, err := m.Run(ctx)
	if err != nil {
		// A failed pass is retried on the next start; it must not stop the operator.
		slog.Error("ui owner migration failed", "err", err)
		return nil
	}
	slog.Info("ui owner migration done", "converted", stats.Converted, "ambiguous", stats.Ambiguous)
	return nil
}

// uiOwnerKinds are the kinds the generic write API manages.
func uiOwnerKinds() []client.ObjectList {
	return []client.ObjectList{
		&agentorcav1alpha1.AgentList{},
		&agentorcav1alpha1.ToolList{},
		&agentorcav1alpha1.MCPServerList{},
		&agentorcav1alpha1.ModelProviderList{},
		&agentorcav1alpha1.KnowledgeBaseList{},
		&agentorcav1alpha1.ModelSelectorList{},
		&agentorcav1alpha1.AgentDeploymentList{},
		&agentorcav1alpha1.AgentWorkflowList{},
	}
}

// gitOpsTracked reports whether a GitOps tool tracks the object.
func gitOpsTracked(obj client.Object) bool {
	a, l := obj.GetAnnotations(), obj.GetLabels()
	_, argo := a["argocd.argoproj.io/tracking-id"]
	_, helm := a["meta.helm.sh/release-name"]
	_, fluxKustomize := l["kustomize.toolkit.fluxcd.io/name"]
	_, fluxHelm := l["helm.toolkit.fluxcd.io/name"]
	return argo || helm || fluxKustomize || fluxHelm || l["app.kubernetes.io/managed-by"] == "Helm"
}

// uiOwnerCandidate classifies one object. convert is true for a object the old
// UI API made; reason is non-empty for an object that is neither, but looks like
// one and should be reported.
func uiOwnerCandidate(obj client.Object) (convert bool, reason string) {
	if obj.GetLabels()["app.kubernetes.io/managed-by"] != security.ManagedByValue {
		return false, ""
	}
	if tenancy.OwnerOf(obj) != "" || !obj.GetDeletionTimestamp().IsZero() {
		return false, ""
	}
	if metav1.GetControllerOf(obj) != nil {
		return false, "" // a controller made it
	}
	switch {
	case gitOpsTracked(obj):
		return false, "tracked by a GitOps tool"
	case func() bool { _, p := tenancy.TenantOf(obj); return p }():
		return false, "platform-shared, which the UI API cannot create"
	case obj.GetLabels()[LabelManagedBy] == LabelManagedByMCPServer:
		return false, "generated by an MCPServer"
	}
	if _, ok := obj.(*agentorcav1alpha1.AgentWorkflow); ok {
		return false, "an AgentWorkflow may have been created by an agent through the internal API"
	}
	return true, ""
}

// Run does one pass.
func (m *UIOwnerMigration) Run(ctx context.Context) (UIOwnerMigrationStats, error) {
	var stats UIOwnerMigrationStats
	for _, list := range uiOwnerKinds() {
		if err := m.Client.List(ctx, list); err != nil {
			return stats, fmt.Errorf("listing %T: %w", list, err)
		}
		items, err := meta.ExtractList(list)
		if err != nil {
			return stats, err
		}
		for _, it := range items {
			obj, ok := it.(client.Object)
			if !ok {
				continue
			}
			convert, reason := uiOwnerCandidate(obj)
			if reason != "" {
				stats.Ambiguous++
				slog.Info("ui owner migration: left unconverted", "kind", fmt.Sprintf("%T", obj),
					"namespace", obj.GetNamespace(), "name", obj.GetName(), "reason", reason,
					"fix", "annotate it "+tenancy.AnnotationOwner+"="+tenancy.OwnerUI+" by hand if the UI should own it")
				continue
			}
			if !convert {
				continue
			}
			if err := m.convert(ctx, obj); err != nil {
				// One object failing (a webhook denial, say) does not stop the rest.
				slog.Warn("ui owner migration: converting failed", "kind", fmt.Sprintf("%T", obj),
					"namespace", obj.GetNamespace(), "name", obj.GetName(), "err", err)
				continue
			}
			stats.Converted++
		}
	}
	return stats, nil
}

// convert swaps the managed-by label for the owner annotation.
func (m *UIOwnerMigration) convert(ctx context.Context, obj client.Object) error {
	orig, ok := obj.DeepCopyObject().(client.Object)
	if !ok {
		return fmt.Errorf("%T is not a client.Object", obj)
	}
	l := obj.GetLabels()
	delete(l, "app.kubernetes.io/managed-by")
	obj.SetLabels(l)
	a := obj.GetAnnotations()
	if a == nil {
		a = map[string]string{}
	}
	a[tenancy.AnnotationOwner] = tenancy.OwnerUI
	obj.SetAnnotations(a)
	return m.Client.Patch(ctx, obj, client.MergeFrom(orig))
}
